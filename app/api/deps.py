from __future__ import annotations

from datetime import datetime, timezone
import time
from typing import Optional

from fastapi import Header, HTTPException, Query

from app.services import auth_store


def _now_iso() -> str:
    return datetime.now(tz=timezone.utc).isoformat()


def extract_bearer_token(authorization: Optional[str]) -> str:
    if not authorization:
        raise HTTPException(status_code=401, detail="missing_token")
    if not authorization.lower().startswith("bearer "):
        raise HTTPException(status_code=401, detail="invalid_token")
    token = authorization.split(" ", 1)[1].strip()
    if not token:
        raise HTTPException(status_code=401, detail="invalid_token")
    return token


def require_user(authorization: Optional[str] = Header(default=None)) -> auth_store.StoredUser:
    token = extract_bearer_token(authorization)
    user = auth_store.get_user_by_token(token)
    if not user:
        raise HTTPException(status_code=401, detail="invalid_token")
    auth_store.touch_session(token, _now_iso())
    return user


def require_user_with_token(authorization: Optional[str] = Header(default=None)) -> tuple[str, auth_store.StoredUser]:
    token = extract_bearer_token(authorization)
    user = auth_store.get_user_by_token(token)
    if not user:
        raise HTTPException(status_code=401, detail="invalid_token")
    auth_store.touch_session(token, _now_iso())
    return token, user


def require_user_header_or_query(
    authorization: Optional[str] = Header(default=None),
    access_token: Optional[str] = Query(default=None),
) -> auth_store.StoredUser:
    # Useful for <video>/<audio> tags where the browser cannot attach custom
    # Authorization headers. Prefer Authorization for API calls; use
    # access_token only for media/file URLs generated by the frontend.
    token = str(access_token or "").strip()
    if not token:
        token = extract_bearer_token(authorization)
    user = auth_store.get_user_by_token(token)
    if not user:
        raise HTTPException(status_code=401, detail="invalid_token")
    auth_store.touch_session(token, _now_iso())
    return user


_RATE_BUCKETS: dict[tuple[str, str], list[float]] = {}


def assert_rate_limit(identity: str, scope: str, *, limit: int, window_seconds: int) -> None:
    """Small in-process rate limiter for expensive local endpoints.

    This is intentionally conservative infrastructure for the local API. It is
    not a replacement for a reverse-proxy / Redis rate limiter in multi-process
    production deployments, but it prevents accidental bursts from the UI from
    spawning too many costly jobs or TTS calls in a single process.
    """
    if limit <= 0 or window_seconds <= 0:
        return
    now = time.monotonic()
    key = (str(identity or "anonymous").lower(), str(scope or "default"))
    cutoff = now - float(window_seconds)
    bucket = [ts for ts in _RATE_BUCKETS.get(key, []) if ts >= cutoff]
    if len(bucket) >= limit:
        raise HTTPException(status_code=429, detail="rate_limited")
    bucket.append(now)
    _RATE_BUCKETS[key] = bucket
